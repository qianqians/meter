// 从 schema/methods.yaml 生成 method 常量（TS + Go）。
//
// 为什么不用 YAML 库：这个文件的结构是我们自己定的、极其规整（methods 列表 + 少量标量），
// 一个几十行的容错解析器就够，省掉一个构建期依赖。解析不出来会直接报错，不会静默生成空表。
//
// ⚠️ msg_type 的常量**不在这里生成**：权威定义是 schema/pb/envelope.proto 的 `MsgType` enum，
// 由 protoc-gen-es / protoc-gen-go 生成。一份权威定义，胜过两份镜像。
// 这里的 `msg_types` 镜像只用来校验每条 method 的 msg_type 拼写。
//
// 用法：node gen-methods.mjs <out.ts> <out.go>

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const [outTs, outGo] = process.argv.slice(2);
if (!outTs || !outGo) {
  console.error('用法: node gen-methods.mjs <out.ts> <out.go>');
  process.exit(2);
}

const src = readFileSync(new URL('./methods.yaml', import.meta.url), 'utf8')
  .split('\n')
  .map((l) => l.replace(/\s+#.*$/, '').replace(/^\s*#.*$/, '') + '\n');

// ---------- 极简 YAML 解析（只支持本文件用到的结构） ----------
const msgTypes = {};
const methods = [];
let section = null;

for (const raw of src) {
  const line = raw.replace(/\n$/, '');
  if (!line.trim()) continue;

  if (/^[a-zA-Z_]+:/.test(line)) {
    section = line.slice(0, line.indexOf(':')).trim();
    if (section === 'retired') section = null;
    continue;
  }
  if (/^\s{2}[A-Z_0-9]+:\s*\d+$/.test(line) && section === 'msg_types') {
    const [k, v] = line.trim().split(':');
    msgTypes[k.trim()] = Number(v.trim());
    continue;
  }
  if (section === 'methods') {
    const item = line.match(/^\s{2}- (\w+):\s*(.+)$/);
    if (item) {
      methods.push({ [item[1].trim()]: item[2].trim() });
      continue;
    }
    const kv = line.match(/^\s{4}(\w+):\s*(.+)$/);
    if (kv && methods.length) {
      methods[methods.length - 1][kv[1].trim()] = kv[2].trim();
      continue;
    }
  }
}

if (!Object.keys(msgTypes).length) throw new Error('methods.yaml: msg_types 镜像解析为空');
if (!methods.length) throw new Error('methods.yaml: methods 解析为空');

const parseCode = (s) => {
  const n = s.startsWith('0x') || s.startsWith('0X') ? parseInt(s, 16) : Number(s);
  if (!Number.isInteger(n) || n <= 0 || n > 0xffffffff) throw new Error(`非法 method code: ${s}`);
  return n;
};

const rows = methods.map((m) => {
  const code = parseCode(m.code);
  if (!m.name) throw new Error(`method 0x${code.toString(16)} 缺少 name`);
  if (!m.msg_type) throw new Error(`method ${m.name} 缺少 msg_type`);
  if (msgTypes[m.msg_type] === undefined) throw new Error(`method ${m.name} 的 msg_type ${m.msg_type} 不在镜像表里`);
  return {
    code,
    name: m.name,
    msgType: m.msg_type,
    msgTypeNum: msgTypes[m.msg_type],
    req: m.req === 'null' ? null : m.req,
    rsp: m.rsp === 'null' ? null : m.rsp,
    dir: m.dir ?? '',
  };
});

const seen = new Set();
for (const r of rows) {
  const k = r.code.toString(16);
  if (seen.has(k)) throw new Error(`method code 重复: 0x${k}`);
  seen.add(k);
}

const hex = (n) => `0x${n.toString(16).padStart(4, '0')}`;
const tsLines = rows.map((r) => `  ${r.name}: ${hex(r.code)},`).join('\n');
const tsMeta = rows
  .map((r) => `  ${hex(r.code)}: { name: ${JSON.stringify(r.name)}, code: ${hex(r.code)}, msgType: ${r.msgTypeNum}, req: ${r.req ? JSON.stringify(r.req) : 'null'}, rsp: ${r.rsp ? JSON.stringify(r.rsp) : 'null'}, dir: ${JSON.stringify(r.dir)} },`)
  .join('\n');

const ts = `// 由 schema/gen-methods.mjs 从 methods.yaml 生成，不要手改。
// msg_type 的常量请直接用 envelope_pb.ts 里由 MsgType enum 生成的那份。

export const METHOD = {
${tsLines}
} as const;
export type MethodName = keyof typeof METHOD;
export type MethodCode = (typeof METHOD)[MethodName];

export interface MethodMeta {
  readonly name: string;
  readonly code: number;
  readonly msgType: number;
  readonly req: string | null;
  readonly rsp: string | null;
  readonly dir: string;
}

export const METHOD_META: Readonly<Record<number, MethodMeta>> = {
${tsMeta}
};

/** 方法名 → code；未知名字返回 undefined（调用点应直接抛错，不要兜底猜） */
export function methodCode(name: MethodName): MethodCode {
  return METHOD[name];
}
/** code → 方法元信息；未知 code 返回 undefined（接收端据此丢弃并计数，见 protocol-map §4.5-3） */
export function methodMeta(code: number): MethodMeta | undefined {
  return METHOD_META[code];
}
`;

const goConsts = rows.map((r) => `\tMethod${r.name} uint32 = ${hex(r.code)}`).join('\n');
const goNames = rows.map((r) => `\t${hex(r.code)}: "${r.name}",`).join('\n');

const go = `// Code generated by schema/gen-methods.mjs from methods.yaml. DO NOT EDIT.
package pb

// msg_type 的常量由 protoc-gen-go 从 envelope.proto 的 MsgType enum 生成
// （MsgType_MSG_REQUEST 等），本文件只负责 method code。

// Method codes（唯一源：schema/methods.yaml）
const (
${goConsts}
)

// MethodName 便于日志与排障；接收端遇到不在表里的 code 应丢弃并计数。
var MethodName = map[uint32]string{
${goNames}
}
`;

mkdirSync(dirname(outTs), { recursive: true });
mkdirSync(dirname(outGo), { recursive: true });
writeFileSync(outTs, ts);
writeFileSync(outGo, go);
console.log(`methods.yaml → ${rows.length} 个 method（TS: ${outTs}，Go: ${outGo}）`);
